# SECTION 3: STAGE 1 - DATA EXTRACTION & COHORT CURATION
# ==============================================================================

# Render Stage 1: Data Extraction and Cohort Preparation
# Script: 1_data_extraction_code.Rmd
#
# Operations performed:
# 1. Imports raw simulated EHR tables from 'Assessment_sample/' (patient demographics,
#    therapy records, clinical events, consultation dates).
# 2. Imports clinical and drug code lists from 'Codelists/'.
# 3. Defines study index date (first prescription of PPI or H2RA) and exposure group.
# 4. Derives baseline covariates: age at index, sex, BMI, IMD/SES quintile,
#    ethnicity, prior consultation rate, and comorbidities (gastric cancer,
#    GERD, peptic ulcer disease).
# 5. Establishes study follow-up endpoints, censoring criteria (death, transfer out,
#    study end, or drug switching), and follow-up time (time-to-event).
# 6. Applies study eligibility criteria to generate the final analytical cohort.
# 7. Exports the final cleaned dataset as 'analysis_data.Rds' and compiles
#    '1_data_extraction_code.html'.
#
# Parameters:
# - input: Path to the R Markdown file to render ("1_data_extraction_code.Rmd")
rmarkdown::render("1_data_extraction_code.Rmd")


# ==============================================================================
# SECTION 4: STAGE 2 - STATISTICAL ANALYSIS & MODELING
# ==============================================================================

# Render Stage 2: Statistical Modeling, Diagnostics, and Visualization
# Script: 2_data_analysis_code.Rmd
#
# Operations performed:
# 1. Loads the processed dataset ('analysis_data.Rds') produced in Stage 1.
# 2. Generates descriptive statistics and baseline characteristics table (Table 1).
# 3. Estimates non-parametric survival functions (Kaplan-Meier survival curves
#    and log-rank tests comparing PPI vs H2RA users).
# 4. Fits multivariable Cox proportional hazards regression models (crude,
#    minimally adjusted, fully adjusted, and step-down models).
# 5. Assesses Cox model assumptions:
#    - Functional form / linearity of continuous covariates via Martingale residuals
#      and natural cubic splines.
#    - Proportional hazards assumption via Schoenfeld residuals and log-log plots.
# 6. Implements stratified Cox models and tests for interaction terms.
# 7. Generates predicted survival curves for specified hypothetical patient profiles.
# 8. Saves all publication tables and figures to the '2. Figures/' directory and
#    compiles '2_data_analysis_code.html'.
#
# Parameters:
# - input: Path to the R Markdown file to render ("2_data_analysis_code.Rmd")
rmarkdown::render("2_data_analysis_code.Rmd")
